package org.jwellman.virtualdesktop.docking;

/**
 * Available themes for the docking framework.
 *
 * @author Rick Wellman
 */
public enum DockingTheme {
    /** Flat theme - modern design without animations */
    FLAT,

    /** Eclipse theme - Eclipse IDE style */
    ECLIPSE,

    /** Smooth theme - flat with animations */
    SMOOTH,

    /** Basic theme - minimal styling */
    BASIC,

    /** Bubble theme - includes drag/drop highlighting */
    BUBBLE
}
